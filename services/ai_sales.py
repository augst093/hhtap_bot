        example = ACTION_EXAMPLES.get(action, ACTION_EXAMPLES["insta"])
        return f"{BASE_SYSTEM_PROMPT}\n\n{example}\n\nВыдавай ТОЛЬКО чистый текст сообщения из 3 абзацев без заголовков."

