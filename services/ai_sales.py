_CITY_TOKENS = {"ташкент", "tashkent", "toshkent", "тоshkent", "узбекистан", "uzbekistan", "o'zbekiston", "oʻzbekiston"}

_UZ_DIGRAPHS = [
    ("o'", "о"), ("g'", "г"), ("sh", "ш"), ("ch", "ч"), ("yo", "ё"), ("yu", "ю"),
    ("ya", "я"), ("ye", "е"), ("ts", "ц"), ("ng", "нг"),
]
_UZ_LETTERS = {
    "a": "а", "b": "б", "d": "д", "e": "е", "f": "ф", "g": "г", "h": "х", "i": "и",
    "j": "ж", "k": "к", "l": "л", "m": "м", "n": "н", "o": "о", "p": "п", "q": "к",
    "r": "р", "s": "с", "t": "т", "u": "у", "v": "в", "x": "х", "y": "й", "z": "з",
    "c": "к", "w": "в",
}


def uz_latin_to_cyrillic(text: str) -> str:
    """Sultonali Mashxadiy -> Султонали Машхадий. Кириллица остаётся как есть."""
    if not re.search(r"[A-Za-z]", text):
        return text
    words = []
    for word in re.sub(r"[‘’ʻʼ`]", "'", text).split():
        if word.upper() in ("NFC", "QR", "VIP", "SMS", "IT", "PR", "SMM", "PDF"):
            words.append(word.upper())
            continue
        low = word.lower()
        out, i = "", 0
        while i < len(low):
            for lat, cyr in _UZ_DIGRAPHS:
                if low.startswith(lat, i):
                    out += cyr
                    i += len(lat)
                    break
            else:
                ch = low[i]
                if ch == "e" and i == 0:
                    out += "э"
                elif ch == "y" and i + 1 < len(low) and low[i + 1] in "aeiou":
                    out += "й"
                else:
                    out += _UZ_LETTERS.get(ch, "" if ch == "'" else ch)
                i += 1
        words.append(out[:1].upper() + out[1:] if word[:1].isupper() else out)
    return " ".join(words)


def clean_address(raw_address: Optional[str]) -> Optional[str]:
    """Возвращает человеческое название улицы/района на кириллице или None, если адрес — просто город."""
    if not raw_address:
        return None
    parts = [p.strip() for p in raw_address.split(",") if p.strip()]
    for part in parts:
        low = part.lower()
        if low in _CITY_TOKENS or re.fullmatch(r"\d{5,6}", part):
            continue
        street = re.sub(r"^(ул\.?|улица|проспект|пр-т|пр\.)\s*", "", part, flags=re.IGNORECASE)
        street = re.sub(r"\s+(ko[‘'ʻ`’]?chasi|shoh\s+ko[‘'ʻ`’]?chasi|kochasi|улица|ул\.?|mavzesi|massivi)\b.*$", "", street, flags=re.IGNORECASE)
        street = re.sub(r"[\s,]*\d+[a-zA-Zа-яА-Я/]*$", "", street).strip()
        if street and not street.isdigit() and street.lower() not in _CITY_TOKENS:
            return uz_latin_to_cyrillic(street)
    return None


def detect_niche(name: str) -> str:
    low = name.lower()
    for key, data in NICHES.items():
        if any(k in low for k in data["keywords"]):
            return key
    return "restaurant"


def analyze_venue_context(
    name: str,
    address: str,
    rating: Optional[float] = None,
    reviews_count: Optional[int] = None,
) -> Dict[str, Any]:
    """Превращает сырые данные парсера в плотный коммерческий бриф с точным расчётом 5⭐️."""
    clean_name = (name or "").strip().strip('"\'«»') or "заведение"
    street = clean_address(address)
    loc = f"на {street}" if street else "в Ташкенте"
    niche = detect_niche(clean_name)

    has_data = rating is not None and reviews_count
    needed_to_target = 25
    target_rating = 4.5

    if not has_data:
        facts = "Точных цифр рейтинга в парсере нет — не называй точное число отзывов, делай упор на то, что 95% довольных клиентов уходят без оценки в Гугле."
        allowed_archetypes = ["traffic_leak", "qr_vs_nfc", "reputation_boost", "direct_audit"]
    elif rating < 4.5:
        target_rating = 4.5
        needed_to_target = max(5, int(math.ceil((reviews_count * (4.5 - rating)) / 0.5)))
        facts = (
            f"В Гугл Картах сейчас оценка {rating:.1f} при {reviews_count} отзывах. "
            f"Чтобы перекрыть старые оценки и выйти на {target_rating:.1f}, нужно около {needed_to_target} пятёрок "
            f"(с нашей NFC-картой это закрывается буквально за несколько рабочих смен)."
        )
        allowed_archetypes = ["reputation_boost", "traffic_leak", "qr_vs_nfc", "direct_audit"]
    elif reviews_count < 80:
        target_rating = 4.8 if rating < 4.8 else 4.9
        needed_to_target = max(30, 100 - reviews_count)
        facts = (
            f"Рейтинг хороший ({rating:.1f}), но отзывов пока всего {reviews_count} — карточка выглядит полупустой на фоне соседей, "
            f"а любая случайная низкая оценка сразу собьёт рейтинг. Покажи, как быстро собрать первые +{needed_to_target} пятёрок."
        )
        allowed_archetypes = ["traffic_leak", "direct_audit", "qr_vs_nfc"]
    else:
        target_rating = 4.8
        needed_to_target = 35
        facts = f"Сильная карточка — рейтинг {rating:.1f} и {reviews_count} отзывов. Сделай упор на автоматизацию сбора свежих отзывов без QR-наклеек и без нагрузки на персонал."
        allowed_archetypes = ["qr_vs_nfc", "traffic_leak", "direct_audit"]

    return {
        "clean_name": clean_name,
        "street": street,
        "loc": loc,
        "niche": niche,
        "rating": rating,
        "reviews_count": reviews_count,
        "needed_to_target": needed_to_target,
        "target_rating": target_rating,
        "facts": facts,
        "allowed_archetypes": allowed_archetypes,
    }


def _num_to_words_ru(n: int) -> str:
    """Преобразует число в текст для голосового сообщения (ГС)."""
    mapping = {
        5: "пять", 6: "шесть", 7: "семь", 8: "восемь", 9: "девять", 10: "десять",
        11: "одиннадцать", 12: "двенадцать", 13: "тринадцать", 14: "четырнадцать",
        15: "пятнадцать", 16: "шестнадцать", 17: "семнадцать", 18: "восемнадцать",
        19: "девятнадцать", 20: "двадцать", 25: "двадцать пять", 30: "тридцать",
        35: "тридцать пять", 40: "сорок", 45: "сорок пять", 50: "пятьдесят",
        60: "шестьдесят", 70: "семьдесят", 80: "восемьдесят", 90: "девяносто", 100: "сто",
    }
    if n in mapping:
        return mapping[n]
    rounded = max(10, min(100, int(round(n / 5.0) * 5)))
    return mapping.get(rounded, "несколько десятков")


