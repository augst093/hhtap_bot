                f"- Заведение: «{clean_name}»\n"
                f"- Локация: {loc}\n"
                f"- Ситуация на картах: {ctx['situation']}\n"
                f"- Упущенная выгода: {ctx['pain']}\n"
                f"- Решение: {ctx['solution']}\n"
