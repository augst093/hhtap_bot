    def __init__(self) -> None:
        self._archetype_decks: Dict[str, List[str]] = {}

    def _pick_archetype(self, name: str, allowed: List[str]) -> str:
        deck = self._archetype_decks.get(name)
        if not deck:
            deck = list(allowed)
            random.shuffle(deck)
            self._archetype_decks[name] = deck
        return deck.pop()

