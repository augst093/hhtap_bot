    @staticmethod
    def _postprocess(raw: str, venue_name: str = "") -> str:
        """Мгновенная детерминированная зачистка текста без повторного вызова API."""
        text = raw.strip()
        text = re.sub(r"^```[a-zA-Z]*\s*|\s*```$", "", text).strip()
        if len(text) > 1 and text[0] in "\"'«" and text[-1] in "\"'»":
            text = text[1:-1].strip()

        text = text.replace("**", "").replace("__", "").replace("`", "")
        text = text.replace("«", "").replace("»", "").replace('"', "")

        text = re.sub(r"Google\s+Maps", "Гугл Картах", text, flags=re.IGNORECASE)
        text = re.sub(r"Google\s+Карт", "Гугл Карт", text, flags=re.IGNORECASE)
        text = re.sub(r"\bGoogle\b", "Гугл", text, flags=re.IGNORECASE)

        text = re.sub(r"^(Салам|Приветствую|Привет)(,\s*ребята)?[!.,]?\s*", "Добрый день. ", text, flags=re.IGNORECASE)

        clean_v = (venue_name or "").strip().strip('"\'«»')
        if clean_v and len(clean_v) >= 3:
            text = re.sub(rf"\s*{re.escape(clean_v)}\b", "", text, flags=re.IGNORECASE)

        text = re.sub(r"\n{3,}", "\n\n", text)
        text = re.sub(r" {2,}", " ", text)
        return text.strip()

    async def _call_api(self, action: str, user_prompt: str) -> Optional[str]:
        """
        Пытается получить ответ от Anymodel.org с коротким таймаутом (12 сек)
        и облегчённым промптом. Если сервер Anymodel лежит или перегружен —
        возвращает None, чтобы мгновенно сработал встроенный генератор без ошибки в чате.
        """
        api_key = config.anymodel_api_key.strip()
        if not api_key or api_key == "your_anymodel_api_key_here":
            return None

        endpoint = f"{config.anymodel_base_url.rstrip('/')}/chat/completions"
        primary_model = config.anymodel_model.strip() or "cx/gpt-6-luna"
        system_prompt = self.build_system_prompt(action)

        messages = [
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": user_prompt},
        ]

        headers = {
            "Authorization": f"Bearer {api_key}",
            "Content-Type": "application/json",
            "Accept": "application/json",
            "User-Agent": "HHtapBot/1.0",
        }

        payload = {
            "model": primary_model,
            "messages": messages,
            "temperature": TEMPERATURE,
            "max_tokens": MAX_TOKENS,
        }

        try:
            async with httpx.AsyncClient(timeout=httpx.Timeout(12.0, connect=6.0)) as client:
                response = await client.post(endpoint, headers=headers, json=payload)
            if response.status_code == 200:
                content = response.json()["choices"][0]["message"]["content"]
                if content and len(content.strip()) > 40:
                    return content
            logger.warning(
                "Anymodel API вернул статус %s, переключаемся на мгновенный встроенный генератор HHtap.",
                response.status_code,
            )
        except Exception as e:
            logger.warning(
                "Anymodel API не ответил за 12 сек (%s), используем мгновенный встроенный генератор HHtap.",
                e,
            )

        return None

    async def generate_message(
        self,
        action: str,
        name: str,
        address: str,
        rating: Optional[float] = None,
        reviews_count: Optional[int] = None,
        objection_type: Optional[str] = None,
    ) -> str:
        user_prompt = self.build_user_prompt(action, name, address, rating, reviews_count, objection_type)
        logger.info("AI sales: action=%s venue='%s'", action, name)

        raw = await self._call_api(action, user_prompt)
        if raw:
            return self._postprocess(raw, venue_name=name)

        # Безотказный фоллбэк: если Anymodel перегружен, мгновенно отдаём персонализированный питч
        fallback_text = self.generate_smart_local_message(
            action=action,
            name=name,
            address=address,
            rating=rating,
            reviews_count=reviews_count,
        )
        return self._postprocess(fallback_text, venue_name=name)


