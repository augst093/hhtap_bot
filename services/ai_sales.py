_CITY_TOKENS = {"ташкент", "tashkent", "toshkent", "узбекистан", "uzbekistan", "o'zbekiston", "oʻzbekiston"}


def clean_address(raw_address: Optional[str]) -> Optional[str]:
    """Возвращает человеческое название улицы/района или None, если адрес — просто город."""
    if not raw_address:
        return None
    parts = [p.strip() for p in raw_address.split(",") if p.strip()]
    for part in parts:
        low = part.lower()
        if low in _CITY_TOKENS or re.fullmatch(r"\d{5,6}", part):
            continue
        street = re.sub(r"^(ул\.?|улица|проспект|пр-т|пр\.)\s*", "", part, flags=re.IGNORECASE)
        street = re.sub(r"\s+(ko[‘'ʻ`’]?chasi|shoh\s+ko[‘'ʻ`’]?chasi|kochasi|улица|ул\.?|mavzesi|massivi)\b.*$", "", street, flags=re.IGNORECASE)
        street = re.sub(r"[\s,]*\d+[a-zA-Zа-яА-Я/]*$", "", street).strip()
        if street and not street.isdigit() and street.lower() not in _CITY_TOKENS:
            return uz_latin_to_cyrillic(street)
    return None


_UZ_DIGRAPHS = [
    ("o'", "о"), ("g'", "г"), ("sh", "ш"), ("ch", "ч"), ("yo", "ё"), ("yu", "ю"),
    ("ya", "я"), ("ye", "е"), ("ts", "ц"), ("ng", "нг"),
]
_UZ_LETTERS = {
    "a": "а", "b": "б", "d": "д", "e": "е", "f": "ф", "g": "г", "h": "х", "i": "и",
    "j": "ж", "k": "к", "l": "л", "m": "м", "n": "н", "o": "о", "p": "п", "q": "к",
    "r": "р", "s": "с", "t": "т", "u": "у", "v": "в", "x": "х", "y": "й", "z": "з",
    "c": "к", "w": "в",
}


def uz_latin_to_cyrillic(text: str) -> str:
    """Sultonali Mashxadiy -> Султонали Машхадий. Кириллица остаётся как есть."""
    if not re.search(r"[A-Za-z]", text):
        return text
    words = []
    for word in re.sub(r"[‘’ʻʼ`]", "'", text).split():
        low = word.lower()
        out, i = "", 0
        while i < len(low):
            for lat, cyr in _UZ_DIGRAPHS:
                if low.startswith(lat, i):
                    out += cyr
                    i += len(lat)
                    break
            else:
                ch = low[i]
                if ch == "e" and i == 0:
                    out += "э"
                elif ch == "y" and i + 1 < len(low) and low[i + 1] in "aeiou":
                    out += "й"
                else:
                    out += _UZ_LETTERS.get(ch, "" if ch == "'" else ch)
                i += 1
        words.append(out[:1].upper() + out[1:])
    return " ".join(words)


def detect_niche(name: str) -> str:
    low = name.lower()
    for key, data in NICHES.items():
        if any(k in low for k in data["keywords"]):
            return key
    return "restaurant"


def analyze_venue_context(
    name: str,
    address: str,
    rating: Optional[float] = None,
    reviews_count: Optional[int] = None,
) -> Dict[str, Any]:
    """Превращает сырые данные парсера в смысловой бриф без утечки технических значений."""
    clean_name = (name or "").strip().strip('"\'«»') or "заведение"
    street = clean_address(address)
    loc = f"на {street}" if street else "в Ташкенте"
    niche = detect_niche(clean_name)

    has_data = rating is not None and reviews_count
    if not has_data:
        angle = "no_data"
        facts = "Точных цифр по их карточке в Гугл Картах нет — НЕ называй рейтинг и количество отзывов и не говори, что карточка пустая."
        problem = "Через зал проходит гораздо больше довольных гостей, чем оставляет отзывы в Гугле; довольные просто уходят, не найдя, где оценить."
        allowed_archetypes = ["product", "question", "staff_pain", "math"]
    elif rating < 4.5:
        angle = "low_rating"
        facts = f"Рейтинг в Гугл Картах {rating:.1f}, отзывов {reviews_count}. Можно упомянуть рейтинг."
        problem = "Недовольные пишут сами, довольные молчат — поэтому оценка ниже, чем реальный уровень. Не критикуй заведение."
        allowed_archetypes = ["question", "staff_pain", "math", "product"]
    elif reviews_count < 80:
        angle = "few_reviews"
        facts = f"Рейтинг {rating:.1f} (хороший), отзывов всего {reviews_count}. Можно назвать эти цифры."
        problem = "Оценка отличная, но отзывов мало относительно потока — в поиске по району выше выходят места с бОльшим числом отзывов."
        allowed_archetypes = ["neighbors", "math", "product", "question"]
    else:
        angle = "leader"
        facts = f"Рейтинг {rating:.1f}, отзывов {reviews_count} — сильная карточка. Можно коротко и по-деловому отметить это."
        problem = "Держать темп свежих отзывов без того, чтобы персонал просил гостей и без наклеек с QR. Свежие отзывы важнее старых."
        allowed_archetypes = ["staff_pain", "question", "product"]

    if not street and "neighbors" in allowed_archetypes:
        allowed_archetypes.remove("neighbors")

    return {
        "clean_name": clean_name,
        "street": street,
        "loc": loc,
        "niche": niche,
        "angle": angle,
        "facts": facts,
        "problem": problem,
        "allowed_archetypes": allowed_archetypes,
    }


