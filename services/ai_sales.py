class AISalesService:
    """Генерация плотных B2B-сообщений через OpenAI-совместимый API Anymodel.org."""

    def __init__(self) -> None:
        self._decks: Dict[str, List[Any]] = {}

    def _pick_from_deck(self, key: str, items: List[Any]) -> Any:
        deck = self._decks.get(key)
        if not deck:
            deck = list(items)
            random.shuffle(deck)
            self._decks[key] = deck
        return deck.pop()

