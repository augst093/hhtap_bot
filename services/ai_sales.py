def clean_address(raw_address: str) -> str:
    """
    Превращает сырой адрес в естественную городскую локацию (улица или район Ташкента).
    Исключает нелепые формулировки вроде «на Ташкент, Tashkent, Узбекистан».
    """
    if not raw_address:
        return "в Ташкенте"
    addr = raw_address.strip()

    # Если адрес просто общий Ташкент / Узбекистан
    if re.match(
        r"^(Ташкент|Tashkent)[\s,]+(Ташкент|Tashkent)?[\s,]+(Узбекистан|Uzbekistan)?$",
        addr,
        re.IGNORECASE,
    ) or addr.lower() in ("ташкент", "tashkent"):
        return "в Ташкенте"

    parts = [p.strip() for p in addr.split(",") if p.strip()]
    filtered = [
        p for p in parts
        if p.lower() not in ("ташкент", "tashkent", "узбекистан", "uzbekistan")
    ]

    if filtered:
        target = filtered[0]
        # Очищаем префиксы улиц
        target = re.sub(
            r"^(ул\.|улица|ko'chasi|проспект|shoh\s+ko'chasi)\s*",
            "",
            target,
            flags=re.IGNORECASE,
        ).strip()
        # Очищаем номера домов в конце (например: "Тараса Шевченко 28" -> "Тараса Шевченко")
        target = re.sub(r"\s+\d+[a-zA-Zа-яА-Я]?$", "", target).strip()
        if target:
            return f"на {target}"

    return "в Ташкенте"


def analyze_venue_context(
    name: str,
    address: str,
    rating: Optional[float] = None,
    reviews_count: Optional[int] = None,
) -> Dict[str, Any]:
    """
    Интеллектуальный анализ профиля заведения.
    Определяет точный психологический угол (Angle) и исключает технические утечки данных.
    """
    clean_name = name.strip(' "\'«»')
    loc = clean_address(address)

    if rating is None or reviews_count is None or reviews_count == 0:
        angle_type = "empty_profile"
        situation = "Карточка заведения на Google Maps почти пустая или совсем без свежих отзывов."
        pain = (
            f"Мимо заведения каждый день проходят сотни людей, экспаты и туристы вбивают поиск мест поблизости в Google Maps. "
            f"Видя пустую точку без отзывов, они не рискуют заходить и уходят к ближайшим соседям {loc}."
        )
        solution = (
            "NFC-карта к счёту/на бар позволяет с первого же дня собирать по 5–10 свежих 5 звёзд прямо у столиков без сканирования QR."
        )
        guideline = (
            "СТРОЖАЙШЕ ЗАПРЕЩЕНО писать слова 'рейтинг не указан' или 'отзывов мало'! "
            "Пиши естественно, как живой гость: 'заметил, что на Google Картах точка пока пустая' или 'в картах совсем нет свежих отзывов'."
        )
    elif rating < 4.6:
        angle_type = "low_rating"
        reviews_display = f"{reviews_count}" if reviews_count else "нескольких"
        situation = f"На Google Картах сейчас обидный рейтинг {rating:.1f}★ ({reviews_display} отзывов)."
        pain = (
            "Недовольные клиенты пишут негатив на эмоциях сразу, а сотни довольных гостей просто уходят, ленясь искать точку в поиске вручную. "
            "Из-за этого общий рейтинг занижен, а новые гости боятся заходить."
        )
        solution = (
            "NFC-карта к счёту позволяет за 1–2 недели перекрыть старые оценки десятками свежих 5 звёзд: "
            "гость касается телефоном счёта при оплате — и окно с 5 звёздами открывается за 1 секунду."
        )
        guideline = (
            "Ни в коем случае не критикуй кухню или сервис заведения! "
            "Сделай упор на то, что заведение классное, а оценка просела исключительно из-за лени довольных гостей."
        )
    elif reviews_count < 60:
        angle_type = "few_reviews"
        situation = f"Хороший рейтинг {rating:.1f}★, но пока всего {reviews_count} отзывов."
        pain = (
            f"Сервис и атмосфера на уровне, но соседи по району за счёт большего числа отзывов ранжируются выше в поиске Google Maps "
            f"и забирают органический поток клиентов."
        )
        solution = (
            "NFC-карта помогает конвертировать каждого третьего довольного гостя в реальный 5-звёздочный отзыв прямо у столика за 1 секунду."
        )
        guideline = (
            f"Похвали за качество, но покажи упущенную выгоду: иметь всего {reviews_count} отзывов {loc} — обидно уступать конкурентам."
        )
    else:
        angle_type = "leader"
        situation = f"Топовый профиль на Google Maps: рейтинг {rating:.1f}★ и {reviews_count} отзывов."
        pain = (
            "Удерживать лидерство и собирать отзывы без раздражающих просьб персонала и без неудобных печатных QR-кодов на столах."
        )
        solution = (
            "Премиальные NFC-карты HHtap к счёту: гость прикладывает телефон при оплате — и окно с 5 звёздами готово за 1 секунду без лишних движений."
        )
        guideline = (
            f"Похвали команду за статус лидера {loc}. Предложи NFC как статусный инструмент, который экономит время официантов и админов."
        )

    return {
        "angle_type": angle_type,
        "clean_name": clean_name,
        "loc": loc,
        "situation": situation,
        "pain": pain,
        "solution": solution,
        "guideline": guideline,
    }


